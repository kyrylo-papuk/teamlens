def split(shots: int = POOL) -> tuple[list[tuple[str, str]], list[tuple[str, str]], list[tuple[str, str]]]:
    """(train, validation, test) as lists of (title, area). ``shots`` is the number of training titles per area."""
    def part(start: int, stop: int) -> list[tuple[str, str]]:
        return [(t, area) for area, titles in TICKETS.items() for t in titles[start:stop]]
    return part(0, min(shots, POOL)), part(POOL, POOL + VALIDATION), part(POOL + VALIDATION, None)
